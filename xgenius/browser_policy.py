def policy_settings(data: dict) -> dict:
    """Normalize only the policy fields; truthy strings/integers are rejected."""
    result = {}
    for key, default in _DEFAULTS.items():
        value = data.get(key, default)
        if type(value) is not bool:
            raise BrowserPolicyError(f'{key} must be a boolean')
        result[key] = value
    return result


def _plain_path(path: Path) -> None:
    for item in reversed((path, *path.parents)):
        try:
            info = item.lstat()
        except FileNotFoundError:
            continue
        if item.is_symlink() or bool(getattr(info, 'st_file_attributes', 0) & 0x400):
            raise BrowserPolicyError('Browser policy paths cannot contain links or reparse points')


def _write(path: Path, text: str) -> None:
    _plain_path(path)
    name = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='\n',
                                         dir=path.parent, prefix='.policy-', delete=False) as handle:
            name = handle.name
            handle.write(text)
        _plain_path(path)
        os.replace(name, path)
    finally:
        if name and os.path.exists(name):
            os.unlink(name)


def prepare_policy_extension(profile_dir: Path, settings: dict) -> Path | None:
    """Recreate this profile's local extension and return its unpacked directory.

    Caller must hold the idle profile lease. Combine the returned directory with
    existing proxy/preset extensions in a single ``--load-extension`` argument.
    With all settings off there is no extension to load; an existing generated
    copy is also neutralized so it cannot retain old rules.
    """
    selected = policy_settings(settings)
    active = any(selected.values())
    directory = Path(os.path.abspath(profile_dir)) / _DIRECTORY
    if not active and not directory.exists():
        return None
    _plain_path(directory)
    rules = []
    resources = [resource for key, resource in (('block_images', 'image'),
                 ('block_media', 'media'), ('block_fonts', 'font')) if selected[key]]
    if resources:
        rules.append({'id': 1, 'priority': 1, 'action': {'type': 'block'},
                      'condition': {'resourceTypes': resources}})
    if selected['phishing_protection']:
        for identifier, guard in enumerate(_GUARDS, 10):
            condition = {'regexFilter': guard['regex'], 'resourceTypes': ['main_frame']}
            if guard.get('excluded'):
                condition['excludedRequestDomains'] = guard['excluded']
            rules.append({'id': identifier, 'priority': 10,
                          'action': {'type': 'redirect', 'redirect': {
                              'regexSubstitution': f'chrome-extension://{_EXTENSION_ID}/warning.html#\\0'}},
                          'condition': condition})
    mask = sum(1 << index for index, key in enumerate(_DEFAULTS) if selected[key])
    manifest = {
        'manifest_version': 3, 'name': 'XAnty local browser policy',
        'version': f'1.0.{mask}', 'minimum_chrome_version': '102', 'key': _PUBLIC_KEY,
        'permissions': ['declarativeNetRequest'],
        'declarative_net_request': {'rule_resources': [
            {'id': f'policy_{mask}', 'enabled': True, 'path': 'rules.json'}]},
        'content_security_policy': {'extension_pages': "script-src 'self'; object-src 'none';"},
    }
    if selected['phishing_protection']:
        manifest.update({
            'permissions': ['declarativeNetRequest', 'storage', 'webNavigation'],
            'host_permissions': ['http://*/*', 'https://*/*'],
            'background': {'service_worker': 'worker.js'},
            'web_accessible_resources': [{'resources': ['warning.html'],
                                         'matches': ['http://*/*', 'https://*/*']}],
        })
    files = {
        'manifest.json': json.dumps(manifest, ensure_ascii=False, indent=2),
        'rules.json': json.dumps(rules, ensure_ascii=False, indent=2),
        'policy.js': _POLICY_JS.replace('/*GUARDS*/', json.dumps(_GUARDS)),
        'worker.js': _WORKER_JS,
        'warning.html': _WARNING_HTML,
        'warning.js': _WARNING_JS,
        'warning.css': _WARNING_CSS,
    }
    # Check every destination before changing any file, including stale files.
    for filename in files:
        _plain_path(directory / filename)
    directory.mkdir(parents=True, exist_ok=True)
    for filename, content in files.items():
        _write(directory / filename, content)
    return directory if active else None


_POLICY_JS = r"""'use strict';
(() => {
  const guards = /*GUARDS*/;
  function networkURL(value) {
    const url = new URL(value);
    if (!['http:', 'https:'].includes(url.protocol)) throw new Error('Invalid address');
    url.hash = '';
    return url.href;
  }
  function assess(value) {
    let url;
    try { url = new URL(value); } catch (_) { return null; }
    if (!['http:', 'https:'].includes(url.protocol)) return null;
    for (const guard of guards) {
      if (guard.excluded?.some(domain => url.hostname === domain || url.hostname.endsWith('.' + domain))) continue;
      if (new RegExp(guard.regex, 'i').test(url.href)) {
        return {url: url.href, host: url.host, reason: guard.reason};
      }
    }
    return null;
  }
  function exactPattern(value) {
    // Chrome's DNR URL may include the navigation fragment. Match the exact
    // network address with or without it; query changes still cannot bypass.
    return '^' + networkURL(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?:#.*)?$';
  }
  globalThis.XGPolicy = Object.freeze({assess, networkURL, exactPattern});
})();
"""


_WORKER_JS = r"""'use strict';
importScripts('policy.js');
const keyFor = tabId => 'navigation:' + tabId;
const latestNavigation = new Map();

async function remember(details) {
  if (details.frameId !== 0 || details.tabId < 0 || !XGPolicy.assess(details.url)) return;
  // storage.session is memory-only and survives MV3 worker suspension. Navigation
  // events retain fragments that may be absent from the DNR network request URL.
  latestNavigation.set(details.tabId, details.url);
  await chrome.storage.session.set({[keyFor(details.tabId)]: details.url});
}

async function clearAllowance(tabId) {
  const rules = await chrome.declarativeNetRequest.getSessionRules();
  const ids = rules.filter(rule => rule.condition.tabIds?.includes(tabId)).map(rule => rule.id);
  if (ids.length) await chrome.declarativeNetRequest.updateSessionRules({removeRuleIds: ids});
}

async function targetFor(sender) {
  if (sender.id !== chrome.runtime.id || !Number.isInteger(sender.tab?.id) || sender.tab.id < 0 || sender.frameId !== 0) return null;
  let source;
  try { source = new URL(sender.url); } catch (_) { return null; }
  if (source.protocol !== 'chrome-extension:' || source.hostname !== chrome.runtime.id ||
      source.pathname !== '/warning.html' || source.search) return null;
  // Do not decodeURIComponent: percent escapes belong to the original URL, and
  // its query and fragment may themselves contain '&', '#', or encoded URLs.
  let value = source.hash.slice(1);
  if (!XGPolicy.assess(value)) return null;
  const stored = await chrome.storage.session.get(keyFor(sender.tab.id));
  const original = latestNavigation.get(sender.tab.id) || stored[keyFor(sender.tab.id)];
  if (typeof original === 'string' && XGPolicy.networkURL(original) === XGPolicy.networkURL(value)) value = original;
  return {...XGPolicy.assess(value), url: value};
}

async function handle(message, sender) {
  const target = await targetFor(sender);
  if (!target || !message || !['view', 'continue', 'back'].includes(message.type)) return {ok: false};
  const tabId = sender.tab.id;
  if (message.type === 'view') return {ok: true, ...target};
  await clearAllowance(tabId);
  if (message.type === 'back') {
    latestNavigation.delete(tabId);
    await chrome.storage.session.remove(keyFor(tabId));
    try { await chrome.tabs.goBack(tabId); }
    catch (_) { await chrome.tabs.update(tabId, {url: 'about:blank'}); }
    return {ok: true};
  }
  // An exact URL, main-frame-only allow in this tab. It does not exempt any
  // subresources, other tabs, changed parameters, or suspicious redirect target.
  const ruleId = tabId || 2147483647;
  await chrome.declarativeNetRequest.updateSessionRules({addRules: [{
    id: ruleId, priority: 1000, action: {type: 'allow'},
    condition: {regexFilter: XGPolicy.exactPattern(target.url),
      isUrlFilterCaseSensitive: true, resourceTypes: ['main_frame'], tabIds: [tabId]}
  }]});
  try { await chrome.tabs.update(tabId, {url: target.url}); }
  catch (error) { await clearAllowance(tabId); throw error; }
  return {ok: true};
}

chrome.runtime.onMessage.addListener((message, sender, reply) => {
  handle(message, sender).then(reply, () => reply({ok: false}));
  return true;
});
chrome.webNavigation.onBeforeNavigate.addListener(details => remember(details).catch(() => {}));
for (const event of [chrome.webNavigation.onCommitted, chrome.webNavigation.onErrorOccurred]) {
  event.addListener(details => {
    if (details.frameId === 0) return clearAllowance(details.tabId).catch(() => {});
  });
}
chrome.tabs.onRemoved.addListener(tabId => {
  latestNavigation.delete(tabId);
  return Promise.all([clearAllowance(tabId), chrome.storage.session.remove(keyFor(tabId))]).catch(() => {});
});
"""


