"""Portable, local Chrome MV3 resource controls and address warnings.

Append ``prepare_policy_extension(...)`` to Chrome's unpacked extension paths.
Rules are static, so resource blocking and warning redirects do not depend on a
running service worker. No request/authentication listeners, remote lists or
telemetry are used. Keep Chrome's native Safe Browsing enabled as well: these
structural address hints cannot establish whether a site is safe or malicious.

The warning covers HTTP(S) main-frame network navigations, not page contents,
downloads, responses generated by a site's service worker, or all phishing.
Internationalized hostnames are intentionally a caution, including legitimate
IDNs, rather than an assertion that the site is malicious. Continue opens the
original address as a navigation; it does not replay a submitted form body.

Chrome APIs used here predate bundled Chrome 128. References:
https://developer.chrome.com/docs/extensions/reference/api/declarativeNetRequest/
https://developer.chrome.com/docs/extensions/reference/api/webNavigation/
https://developer.chrome.com/docs/extensions/reference/api/storage/
https://developer.chrome.com/docs/extensions/reference/manifest/key
"""
